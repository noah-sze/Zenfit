const CHAR_TO_INITIAL = new Map<string, string>();

for (const [initial, chars] of Object.entries(PINYIN_INITIALS_GROUPS)) {
  for (let i = 0; i < chars.length; i++) {
    const ch = chars[i];
    if (!CHAR_TO_INITIAL.has(ch)) {
      CHAR_TO_INITIAL.set(ch, initial);
    }
  }
}

const PINYIN_INITIALS_CACHE = new Map<string, string>();

/**
 * 將中文或其他字串轉換為拼音首字母（全小寫）
 * - 支援英文字母與數字原樣保留（轉為小寫）
 * - 自動忽略空白字元與標點符號
 * - 具備前端記憶體快取 (O(1) 瞬時響應)
 * 
 * @param chineseText 目標文字（如「雞胸肉」、「槓鈴臥推」、「BB Row」）
 * @returns 拼音首字母字串（如「jxr」、「glwt」、「bbrow」）
 */
export function toPinyinInitials(chineseText: string): string {
  if (!chineseText) return '';
  const cached = PINYIN_INITIALS_CACHE.get(chineseText);
  if (cached !== undefined) return cached;

  let result = '';
  for (let i = 0; i < chineseText.length; i++) {
    const ch = chineseText[i];
    if ((ch >= 'a' && ch <= 'z') || (ch >= '0' && ch <= '9')) {
      result += ch;
    } else if (ch >= 'A' && ch <= 'Z') {
      result += ch.toLowerCase();
    } else {
      const initial = CHAR_TO_INITIAL.get(ch);
      if (initial) {
        result += initial;
      }
    }
  }

  if (PINYIN_INITIALS_CACHE.size < 5000) {
    PINYIN_INITIALS_CACHE.set(chineseText, result);
  }
  return result;
}

/**
 * 判斷目標字串是否匹配拼音首字母 Query
 * 
 * @param query 使用者輸入的搜尋字詞（如「jxr」）
 * @param targetText 被搜尋的目標名稱
 */
export function matchesPinyinInitials(query: string, targetText: string): boolean {
  if (!query || !targetText) return false;
  const cleanQ = query.trim().toLowerCase();
  if (!/^[a-z]{2,}$/.test(cleanQ)) return false;

  const targetInitials = toPinyinInitials(targetText);
  return targetInitials.includes(cleanQ);
}
